/** The prefix a custom shelf's key carries. Mirrors CUSTOM_PREFIX in lib/library.ts. */
const CUSTOM_SHELF_PREFIX = "custom-";

/** A topic's name in the reader's language. */
export function topicName(key: string, name: string, lang: Lang): string {
  return lang === "zh" ? TOPIC_ZH[key] ?? name : name;
}

/**
 * A topic's one-line description in the reader's language.
 *
 * A custom shelf (the reader's own) has no entry of its own: it is one line
 * of copy that says so, and it is the same for every one of them.
 */
export function topicBlurb(key: string, blurb: string, lang: Lang): string {
  if (lang !== "zh") return blurb;
  if (key.startsWith(CUSTOM_SHELF_PREFIX)) return "你自己建的书架。";
  return TOPIC_BLURB_ZH[key] ?? blurb;
}

export const LANG_KEY = "gloss:lang";

/** The reader's language: a saved choice, else the browser's, else English. */
export function resolveLang(): Lang {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "zh") return saved;
  } catch {}
  const wanted = navigator.language?.toLowerCase() ?? "";
  return wanted.startsWith("zh") ? "zh" : "en";
}

export const isLang = (v: unknown): v is Lang => v === "en" || v === "zh";

/**
 * A string in the reader's language. `{n}` and `{name}` in the text are filled
 * from `vars`. An unknown key returns the key itself, so a typo shows up on
 * screen instead of rendering as nothing.
 */
export function translate(key: StringKey | string, lang: Lang, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang];
  const template = dict[key as StringKey] ?? en[key as StringKey] ?? (key as string);
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/** The English text, whatever the language: for code that must not be translated. */
export const enText = (key: StringKey): string => en[key];